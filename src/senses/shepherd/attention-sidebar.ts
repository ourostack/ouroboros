import * as fs from "node:fs"
import * as path from "node:path"

const MARKER = "// Generated by Ouro session attention."

/** Opens beside the coding terminal without moving focus; the view then pins a fresh hint. */
export function attentionSidebar(url: string): string {
  const parsed = new URL(url)
  if (parsed.protocol !== "http:" || parsed.hostname !== "127.0.0.1" || !/^[0-9a-f]{64}$/.test(parsed.hash.slice(1))) {
    throw new Error("Attention sidebar requires its private loopback entry.")
  }
  return `${MARKER}
VStack(alignment: .leading, spacing: 12) {
    Text("Ouro").font(.headline)
    Text("Talk about this session without touching its input.").font(.caption).foregroundColor(.secondary)
    ForEach(workspaces.filter { $0.selected }) { w in
        Button(action: { cmux("browser.open_split", focus: false, workspace_id: w.id, url: ${JSON.stringify(url)}) }) {
            Text("Talk to Ouro")
        }
    }
}.padding(16)
`
}

export function installAttentionSidebar(directory: string, url: string, agent = "ouro"): string {
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(agent)) throw new Error("Attention requires a safe agent name.")
  const file = path.join(directory, `ouro-attention-${agent}.swift`)
  fs.mkdirSync(directory, { recursive: true })
  if (fs.existsSync(file) && !fs.readFileSync(file, "utf8").startsWith(MARKER)) {
    throw new Error("An independently authored ouro-attention sidebar already exists; it was not overwritten.")
  }
  const staging = `${file}.pending`
  fs.writeFileSync(staging, attentionSidebar(url), { mode: 0o600 })
  fs.chmodSync(staging, 0o600)
  fs.renameSync(staging, file)
  return file
}
